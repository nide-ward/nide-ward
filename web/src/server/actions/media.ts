"use server";

import { and, eq } from "drizzle-orm";
import { schema } from "@/db";
import { deleteObject, headObject, MAX_UPLOAD_BYTES } from "@/lib/storage";
import { deleteMediaSchema, registerMediaSchema } from "@/lib/validation";
import { ActionError, audit, requireActiveAdmission, runAction, type ActionResult } from "../action";

/** Called after the browser (or the proxy route) has stored the object. Verifies it really exists. */
export async function registerMedia(raw: unknown): Promise<ActionResult<{ id: string }>> {
  return runAction("media.attach", registerMediaSchema, raw, async ({ staff, input, db }) => {
    // Keys are generated by the server as lab/<admissionId>/<uuid>.<ext>; refuse anything else.
    if (!input.objectKey.startsWith(`lab/${input.admissionId}/`) || input.objectKey.includes("..")) {
      throw new ActionError("validation", "Invalid file reference.");
    }
    const head = await headObject(input.objectKey);
    if (!head) throw new ActionError("not_found", "The upload did not complete. Try again.");
    if (head.size <= 0 || head.size > MAX_UPLOAD_BYTES) throw new ActionError("validation", "That file is too large.");
    return db.transaction(async (tx) => {
      await requireActiveAdmission(tx, input.admissionId);
      const [row] = await tx
        .insert(schema.labMedia)
        .values({
          admissionId: input.admissionId,
          objectKey: input.objectKey,
          contentType: input.contentType,
          sizeBytes: head.size,
          originalName: input.originalName,
          uploadedBy: staff.displayName,
        })
        .returning();
      await audit(tx, staff, "media.attach", "lab_media", row.id, null, row);
      return { id: row.id };
    });
  });
}

export async function deleteMedia(raw: unknown): Promise<ActionResult> {
  return runAction("media.delete", deleteMediaSchema, raw, async ({ staff, input, db }) => {
    const row = await db.transaction(async (tx) => {
      await requireActiveAdmission(tx, input.admissionId);
      const [removed] = await tx
        .delete(schema.labMedia)
        .where(and(eq(schema.labMedia.id, input.mediaId), eq(schema.labMedia.admissionId, input.admissionId)))
        .returning();
      if (!removed) throw new ActionError("not_found", "That photo was already removed.");
      await audit(tx, staff, "media.delete", "lab_media", removed.id, removed, null);
      return removed;
    });
    // Best effort: the audit log keeps the object key if the object cannot be removed.
    await deleteObject(row.objectKey).catch((e) => console.warn("Could not delete object", row.objectKey, e));
  });
}
